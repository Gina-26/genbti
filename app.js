  function score() {
    var s = {}, last = {}, tick = 0;
    ORDER.forEach(function (k) { s[k] = 0; last[k] = -1; });
    for (var i = 0; i < answers.length && i < QUESTIONS.length; i++) {
      var opt = QUESTIONS[i].o[answers[i]];
      (opt.t || []).forEach(function (k) { s[k] += 1; last[k] = tick++; });
    }
    // 按“命中次数 / 可命中题数”比，避免选项多的人格占便宜；同比时看次数，再看最后一次命中
    var ratio = function (k) { return s[k] / AVAIL[k]; };
    var best = ORDER[0];
    ORDER.forEach(function (k) {
      var rk = ratio(k), rb = ratio(best);
      if (rk > rb || (rk === rb && (s[k] > s[best] || (s[k] === s[best] && last[k] > last[best])))) best = k;
    });
    if (answers.length > QUESTIONS.length) {
      var hopt = HIDDEN_Q.o[answers[QUESTIONS.length]];
      if (hopt && hopt.h) best = 'paim';
    }
    return { best: best, s: s };
  }

